export function t(key: I18nKey, params?: Record<string, string | number>): string {
  let text: string = (lang() === 'en' ? en : uk)[key];
  if (params) for (const [k, v] of Object.entries(params)) text = text.split(`{${k}}`).join(String(v));
  return text;
}

type PluralForms = { one: string; few?: string; many?: string; other: string };

const PLURALS: Record<string, Record<Lang, PluralForms>> = {
  cards: {
    uk: { one: 'картка', few: 'картки', many: 'карток', other: 'картки' },
    en: { one: 'card', other: 'cards' },
  },
};

/** «5 карток» / «5 cards» з правильною формою множини */
export function countOf(n: number, word: keyof typeof PLURALS): string {
  const forms = PLURALS[word][lang()];
  const rule = new Intl.PluralRules(locale()).select(n) as keyof PluralForms;
  return `${n} ${forms[rule] ?? forms.other}`;
}

/** Назва розділу мовою інтерфейсу */
export function sectionTitle(code: string, fallback: string): string {
  const key = `section.${code}` as I18nKey;
  return key in uk ? t(key) : fallback;
}

/** Коротка мітка розділу для бейджів і фільтрів */
export const sectionBadge = (code: string) => (code === '0' ? t('common.common') : code);

export function formatNumber(n: number): string {
  return new Intl.NumberFormat(locale(), { notation: n >= 10_000 ? 'compact' : 'standard' }).format(n);
}

export function formatDate(d: Date, opts: Intl.DateTimeFormatOptions): string {
  return new Intl.DateTimeFormat(locale(), opts).format(d);
}

