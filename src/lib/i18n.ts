// Двомовний інтерфейс: українська та англійська. Картки (питання/відповіді) лишаються українською.
import { createSignal } from 'solid-js';

export type Lang = 'uk' | 'en';

const STORAGE_KEY = 'fc.lang';

function initialLang(): Lang {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === 'uk' || saved === 'en') return saved;
  } catch {
    // сховище недоступне — визначаємо за мовою системи
  }
  // Для англомовної системи — англійська, для решти — українська
  return navigator.language?.toLowerCase().startsWith('en') ? 'en' : 'uk';
}

const [lang, setLangSignal] = createSignal<Lang>(initialLang());
document.documentElement.lang = lang();

export { lang };

export function setLang(next: Lang): void {
  setLangSignal(next);
  document.documentElement.lang = next;
  try {
    localStorage.setItem(STORAGE_KEY, next);
  } catch {
    // мова діятиме до перезапуску
  }
}

